// The game's statistics (docs/minimal-playthrough.md, M7): how much content the case has, and what each playthrough
// (the annotated reader's action table and the minimal one) asks of a player, by kind and by scene. Written to
// cases/<case>/stats.md by `npm run stats`; engine/stats.test.js checks it is up to date.
//   statsMarkdown(model, {reader, minimal}) → markdown
import { Game } from './game.js';
import { movesOf, readingClicks } from './minimalTable.js';

const n = (x) => x.toLocaleString('en-US');
const count = (list, key) => list.reduce((o, x) => { const k = key(x); o[k] = (o[k] ?? 0) + 1; return o; }, {});
const SECTION_NAMES = { entities: 'people, places and things', events: 'events', claims: 'statements', rules: 'background facts', glosses: 'words explained', propositions: 'propositions', inferences: 'inferences' };
const OPS = [['collect', 'Collect (words clicked)'], ['ask', 'Ask what I know'], ['build', 'Build an inference'], ['notice', 'Mark as odd'], ['raise', 'Raise an exception'], ['seal', 'Seal a check'], ['file', 'File what did not happen'], ['drop', 'Drop a wrong turn'], ['theory', 'Hold a theory'], ['candidate', 'Propose an answer'], ['pose', 'Ask my own question'], ['setAside', 'Set aside'], ['split', 'Split a statement'], ['doubt', 'Doubt'], ['weigh', 'Weigh a theory']];
// A UI step of the tables, by kind (as scripts/ui-run.mjs plays them: each card opened from its list).
const stepKind = (u) => (u.story !== undefined ? 'words clicked' : u.open ? 'card opened from a list' : u.expect ? null : u.select || u.select_text ? 'menu chosen' : u.propose || u.fill ? 'typed' : u.tab ? 'tab chosen' : 'button pressed');
const FAMILIES = { deduction: 'Deductions', notice: 'Odd details', raise: 'Steps seen through', drop: 'Wrong turns dropped', check: 'Checks planned', absence: 'What did not happen' };

export function statsMarkdown(model, { reader, minimal }) {
    const g = new Game(model, { difficulty: 'hard' });
    const d = model.data;
    const paras = g.story.paragraphs.slice(1); // ¶0 is the title
    const words = (p) => p.display.split(/\s+/).filter(Boolean).length;
    let spans = 0;
    for (let i = 1; i < g.story.paragraphs.length; i++) for (const s of g.story.segments(i)) if (s.ids.some((x) => model.cards.has(x))) spans++;
    const sections = count([...model.cards.values()], (c) => c.section);
    const infs = [...g.inferenceById.values()];
    const slots = [...model.slots.values()];
    const tags = Object.entries(count(d.thoughts, (t) => t.tag)).sort((a, b) => b[1] - a[1]);
    const rec = new Game(model, { difficulty: 'hard' });
    const possible = { deduction: rec.score().possible, notice: rec.noticeScore().possible, raise: rec.raiseScore().possible, drop: rec.dropScore().possible, check: rec.checkScore().possible, absence: rec.absenceScore().possible };
    const out = [];
    const line = (s = '') => out.push(s);
    line('# Statistics: Silver Blaze');
    line();
    line('Generated by `npm run stats` (`engine/stats.js`) from the case and the two action tables; do not edit.');
    line();
    line('## The content');
    line();
    line('| | |');
    line('|---|---:|');
    line(`| Paragraphs | ${n(paras.length)} |`);
    line(`| Words | ${n(paras.reduce((a, p) => a + words(p), 0))} |`);
    line(`| Parts, scenes | ${d.parts.length}, ${d.scenes.length} |`);
    line(`| Words a player can click (spans carrying cards) | ${n(spans)} |`);
    line(`| Cards | ${n(model.cards.size)} |`);
    for (const [k, label] of Object.entries(SECTION_NAMES)) line(`| · ${label} | ${n(sections[k] ?? 0)} |`);
    line(`| · · inferences to build / that follow by themselves | ${infs.filter((x) => !x.implicit).length} / ${infs.filter((x) => x.implicit).length} |`);
    line(`| Questions (answers to find) | ${n(slots.length)} |`);
    const tracks = slots.filter((s) => s.track).length;
    line(`| · about the case / the events (who, when, where…) / states (who knew, who held…) | ${d.slots.length} / ${n(slots.length - d.slots.length - tracks)} / ${tracks} |`);
    line(`| Questions the story raises | ${d.questions.length} |`);
    line(`| Theories in the story | ${d.theories.length} |`);
    line(`| Holmes's checks | ${d.checks.length} |`);
    line(`| Puzzles (odd things a story must explain) | ${d.puzzles.length} |`);
    line(`| Absences to file | ${g.absenceById().size} |`);
    line(`| Holmes's steps / with a paragraph to beat | ${d.route.length} / ${g.thoughtScores().length} |`);
    line(`| The annotated reading: thoughts | ${d.thoughts.length} |`);
    line(`| · with prose / quoting the story / with a typed form | ${d.thoughts.filter((t) => t.text).length} / ${d.thoughts.filter((t) => t.reads?.length).length} / ${d.thoughts.filter((t) => t.typed).length} |`);
    line(`| · by kind | ${tags.map(([t, k]) => `${t} ${k}`).join(', ')} |`);
    line();
    line('## The score on Hard');
    line();
    line('| Family | Possible | The reader | The fewest moves |');
    line('|---|---:|---:|---:|');
    for (const [f, label] of Object.entries(FAMILIES)) line(`| ${label} | ${possible[f]} | ${reader.families[f].scored} | ${minimal.families[f].scored} |`);
    line(`| **Ahead of Holmes** | ${Object.values(possible).reduce((a, b) => a + b, 0)} | **${reader.ahead}** | **${minimal.ahead}** |`);
    line();
    const rm = movesOf(reader);
    const mm = movesOf(minimal);
    const rc = count(rm, (m) => m.op);
    const mc = count(mm, (m) => m.op);
    line('## The playthroughs: moves');
    line();
    line('The reader: the annotated reading\'s moves (`action-table.json`). The fewest moves: those of them that still reach');
    line('the maximum, each made as late as its deadlines allow (`action-table-minimal.json`, `docs/minimal-playthrough.md`).');
    line();
    line('| Move | The reader | The fewest moves |');
    line('|---|---:|---:|');
    for (const [op, label] of OPS) if (rc[op] || mc[op]) line(`| ${label} | ${rc[op] ?? 0} | ${mc[op] ?? 0} |`);
    line(`| **Moves** | **${rm.length}** | **${mm.length}** |`);
    line(`| Paragraphs with moves | ${new Set(rm.map((m) => m.at)).size} | ${new Set(mm.map((m) => m.at)).size} |`);
    // Reading: the reader reads a paragraph at a time; the fewest moves jump from one paragraph with moves to the next.
    const reading = readingClicks(g);
    const stops = [...new Set(mm.map((m) => m.at))].sort((a, b) => a - b);
    const jumps = [0, ...stops].reduce((acc, p, i, all) => acc + reading(p + 1, (all[i + 1] ?? g.story.paragraphs.length - 1) + 1), 0);
    line(`| Clicks to read the story (Next paragraph; Next scene, Next deduction) | ${paras.length} | ${jumps} |`);
    line(`| Cards connected in builds | ${rm.filter((m) => m.op === 'build').reduce((a, m) => a + m.cards.length, 0)} | ${mm.filter((m) => m.op === 'build').reduce((a, m) => a + m.cards.length, 0)} |`);
    line(`| Thoughts whose moves are made | ${reader.thoughts.filter((t) => t.moves.length).length} | ${minimal.thoughts.length} |`);
    line(`| Notes and highlights written by the autoplay | ${d.thoughts.reduce((a, t) => a + Math.max((t.reads ?? []).length, (t.typed ?? t.text) ? 1 : 0), 0)} | 0 |`);
    line();
    line('## The playthroughs: steps in the page');
    line();
    line('Each move\'s steps as the tables give them, every card opened from its list (as `scripts/ui-run.mjs` plays them).');
    line('The autoplay takes shorter ways in the fewest-moves playthrough (a card left where it is shown, a link on the card');
    line('in view, the story\'s words) and reads by Next scene and Next deduction; it counts its own clicks and says them at the end.');
    line();
    const steps = (ms) => count(ms.flatMap((m) => m.ui.map(stepKind)).filter(Boolean), (k) => k);
    const rs = steps(rm);
    const ms = steps(mm);
    line('| Step | The reader | The fewest moves |');
    line('|---|---:|---:|');
    for (const k of ['words clicked', 'card opened from a list', 'button pressed', 'menu chosen', 'typed', 'tab chosen']) line(`| ${k} | ${rs[k] ?? 0} | ${ms[k] ?? 0} |`);
    line(`| **Steps** | **${n(Object.values(rs).reduce((a, b) => a + b, 0))}** | **${n(Object.values(ms).reduce((a, b) => a + b, 0))}** |`);
    line();
    line('## By scene');
    line();
    line('| Scene | Paragraphs | Words | Moves: the reader | Moves: the fewest |');
    line('|---|---|---:|---:|---:|');
    const starts = [...g.sceneStarts];
    const end = g.story.paragraphs.length;
    starts.forEach((a, i) => {
        const b = (starts[i + 1] ?? end) - 1;
        const inScene = (m) => m.at >= a && m.at <= b;
        line(`| ${d.scenes[i]?.title ?? `Scene ${i + 1}`} | ¶${a}–${b} | ${n(g.story.paragraphs.slice(a, b + 1).reduce((x, p) => x + words(p), 0))} | ${rm.filter(inScene).length} | ${mm.filter(inScene).length} |`);
    });
    line();
    return out.join('\n');
}
