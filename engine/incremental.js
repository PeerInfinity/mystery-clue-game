// Incremental mode's waits (the 'incremental' pace, Hard only): where the story stops until the player has made a
// move, so that the maximum is reached and no reading can lose a point.
//   - a row: before every deadline of a row that scores on Hard (hints.json's rows), until the row is made;
//   - a keep: before a paragraph where a move a row needs is lost (hints.json's `lost`: the story states the inference
//     it builds, or the implicit inference it gives a premise of), until the player holds that inference (by any
//     route), or every row the move serves is made.
// A wait names what is needed, never the move or the cards: the player's search finds those. Written to
// cases/<case>/incremental.json by scripts/incremental.js (npm run incremental); engine/incremental.test.js checks it
// is up to date and that a player who only moves when the story waits still reaches the maximum.
import { Game } from './game.js';

const key = (thought, family) => `${thought}|${family}`;

/** The moves of the hints' data a set of moves needs, with them (closed over `needs`). */
export function closure(bySeq, seqs) {
    const out = new Set();
    const todo = [...seqs];
    while (todo.length) {
        const s = todo.pop();
        if (out.has(s)) continue;
        out.add(s);
        todo.push(...bySeq.get(s).needs);
    }
    return out;
}

/** → {description, waits: [{para, row} | {para, keep: {inferences}, rows: [row key]}]} from hints.json's data. */
export function incrementalWaits(model, hints) {
    const bySeq = new Map(hints.moves.map((m) => [m.seq, m]));
    const rowOf = new Map(hints.rows.map((r) => [key(r.thought, r.family), r]));
    const serves = new Map();
    for (const [k, r] of rowOf) for (const s of closure(bySeq, r.makes)) (serves.get(s) ?? serves.set(s, []).get(s)).push(k);
    // Where a game that only reads is told each inference (as hintData finds `lost`).
    const g = new Game(model, { difficulty: 'hard' });
    const stated = new Map();
    while (!g.finished()) { g.advance(); for (const id of g.unlocked.keys()) if (!stated.has(id) && g.inferenceById.has(id)) stated.set(id, g.read - 1); }
    const waits = hints.rows.map((r) => ({ para: r.deadline, row: key(r.thought, r.family) }));
    const keeps = new Map();
    for (const m of hints.moves) {
        if (m.lost === undefined) continue;
        // Only rows due after the move is lost: a row due by then has its own wait first.
        const rows = (serves.get(m.seq) ?? []).filter((k) => rowOf.get(k).deadline > m.lost);
        if (!rows.length) continue;
        const inferences = m.op === 'build' ? [m.inference]
            : [...g.inferenceById.values()].filter((k) => k.implicit && stated.get(k.id) === m.lost && k.premises.some((c) => (m.got ?? [m.card]).includes(c))).map((k) => k.id);
        if (!inferences.length) throw new Error(`incremental: move ${m.seq} (${m.op}) is lost at ¶${m.lost}, but gives no inference stated there`);
        // One wait per paragraph and inference, serving every row any of its moves serves.
        for (const inf of inferences) {
            const k = `${m.lost}|${inf}`;
            const w = keeps.get(k) ?? keeps.set(k, { para: m.lost, keep: { inferences: [inf] }, rows: [] }).get(k);
            for (const r of rows) if (!w.rows.includes(r)) w.rows.push(r);
        }
    }
    for (const w of keeps.values()) waits.push({ ...w, rows: w.rows.sort() });
    waits.sort((a, b) => a.para - b.para || (a.row ? 0 : 1) - (b.row ? 0 : 1) || (a.row ?? a.keep.inferences[0]).localeCompare(b.row ?? b.keep.inferences[0], 'en', { numeric: true }));
    return {
        description: 'Incremental mode\'s waits: before each paragraph, the rows to make and the inferences to hold (unless the rows they serve are made). Generated by `npm run incremental` from hints.json; do not edit.',
        waits,
    };
}

/** The file's text: one wait per line. */
export function incrementalJson(data) {
    return `{\n "description": ${JSON.stringify(data.description)},\n "waits": [\n${data.waits.map((w) => `    ${JSON.stringify(w)}`).join(',\n')}\n ]\n}\n`;
}

/**
 * A player who only moves when the story waits: reads on until it stops, then makes the moves of the hints' data that
 * the open waits need (a row's moves, or a kept move, each with what it needs), oldest first. → {game, stuck: null |
 * {para, open}, fails: [seq]}.
 * `make(g, model, m)` makes one move (engine/minimalTable.js's make).
 */
export function playLazy(model, hints, waits, make) {
    const g = new Game(model, { pace: 'incremental', waits: waits.waits });
    const bySeq = new Map(hints.moves.map((m) => [m.seq, m]));
    const rowOf = new Map(hints.rows.map((r) => [key(r.thought, r.family), r]));
    const done = new Set();
    const fails = [];
    while (!g.finished()) {
        if (g.advance().ok) continue;
        const open = g.blockers();
        const seqs = new Set();
        for (const w of open) {
            if (w.row) for (const s of rowOf.get(w.row).makes) seqs.add(s);
            // A keep: the lost moves at this paragraph that give its inference.
            else for (const m of hints.moves) if (m.lost === w.para && (m.inference === w.keep.inferences[0] || (m.op !== 'build' && (g.inferenceById.get(w.keep.inferences[0])?.premises ?? []).some((c) => (m.got ?? [m.card]).includes(c))))) seqs.add(m.seq);
        }
        for (const s of [...closure(bySeq, seqs)].sort((a, b) => a - b)) {
            if (done.has(s)) continue;
            done.add(s);
            if (!make(g, model, bySeq.get(s))) fails.push(s);
        }
        if (g.blockers().length) return { game: g, stuck: { para: g.read, open: g.blockers() }, fails };
    }
    return { game: g, stuck: null, fails };
}
