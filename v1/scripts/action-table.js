// The action table: the annotation's player on Hard, its moves as the UI makes them,
// written to cases/<case>/action-table.json (the autoplay's script). npm run action-table [case dir]
import fs from 'node:fs';
import path from 'node:path';
import { loadCase } from '../engine/loadCase.js';
import { actionTable } from '../engine/actionTable.js';

const dir = process.argv[2] ?? path.join(path.dirname(new URL(import.meta.url).pathname), '../cases/silver-blaze');
const model = await loadCase(dir);
const { table, never } = actionTable(model);
// One thought per line, like the case's other data files.
const head = { description: 'The action table: the annotation\'s thoughts as moves in the UI, on Hard. Generated by `npm run action-table`; do not edit.', difficulty: table.difficulty, families: table.families, ahead: table.ahead };
const lines = table.thoughts.map((t) => `    ${JSON.stringify(t)}`);
fs.writeFileSync(path.join(dir, 'action-table.json'), `${JSON.stringify(head, null, 1).replace(/\n}$/, ',')}\n "thoughts": [\n${lines.join(',\n')}\n ]\n}\n`);
const moves = table.thoughts.reduce((n, t) => n + t.moves.length, 0);
console.log(`wrote action-table.json: ${moves} moves; ahead of Holmes ${table.ahead}; ${Object.entries(table.families).map(([f, a]) => `${f} ${a.scored}/${a.possible}`).join(', ')}${never.length ? `; never held: ${never.join(' ')}` : ''}`);
