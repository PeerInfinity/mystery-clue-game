#!/usr/bin/env node
// Validate a case's annotated reading (thoughts.json) against the case and the story, and write its report.
//
//   node scripts/validate-thoughts.js cases/silver-blaze
//
// Checks (engine/thoughts.js): ids carry their paragraph and scene; tags, subtypes, confidence and profile are
// known; premises and relation targets exist and come no later; every quote is found and none lies ahead; a
// relation to one member of a set names a candidate the target lists; `maps` resolve to case cards; the ids the
// prose cites exist; the data mirrors docs/reading-annotated.md field by field (Round 183). Reports, without failing: how many thoughts of each tag a case card holds,
// where the game deals a RECORD's card later than the reader could have it, and background cards with no rule;
// and the short chains: each deduction-type thought's inference, premises that disagree with what it cites, the
// earliest-date misses, inferences named twice, and inferences no thought names (implicit or not yet marked).
// Writes <case>/thoughts-report.md.

import fs from 'node:fs';
import path from 'node:path';
import { loadCase } from '../engine/loadCase.js';
import { checkThoughts } from '../engine/thoughts.js';
import { render } from '../engine/logic.js';

const dir = process.argv[2];
if (!dir) {
    console.error('usage: validate-thoughts.js <case dir>');
    process.exit(2);
}
const model = await loadCase(dir);
const data = JSON.parse(fs.readFileSync(path.join(dir, 'thoughts.json'), 'utf8'));
const mdPath = new URL('../docs/reading-annotated.md', import.meta.url);
const markdown = fs.existsSync(mdPath) ? fs.readFileSync(mdPath, 'utf8') : null;
const r = checkThoughts(data, model, { markdown, dates: true, implicitRequired: true });

const out = [];
out.push(`# Thoughts report: ${model.data.case.title}`, '', 'Generated by `scripts/validate-thoughts.js`. Do not edit by hand.', '');
out.push(`- thoughts: ${data.thoughts.length}; background cards: ${data.background.length}`);
out.push(`- errors: ${r.errors.length}`, '');
out.push('## Coverage', '', 'Thoughts of each tag whose content some case card holds (`maps`): a claim, rule, inference, question, action, route step or theory. A thought with no card is a gap in the data. Held content is not yet a move the player can make: the moves are the workstreams of `docs/gap-analysis.md`.', '');
out.push('| Tag | Thoughts | Held by a card |', '|---|---|---|');
for (const c of r.coverage) out.push(`| ${c.tag} | ${c.count} | ${c.mapped} |`);
{
    // What the autoplay writes for each thought (docs/autoplay.md A3, Round 186): its prose as it stands, its typed
    // form, a highlight of the words it reads alone, or nothing.
    const T = data.thoughts;
    const n = (f) => T.filter(f).length;
    out.push('', '## Notes the autoplay types', '', 'For each thought, what the autoplay writes into the story: the reader\'s note as it stands (`text`), its typed form (`typed`, where the note cites thoughts, cards or paragraphs, or uses the annotation\'s notation), a highlight of the words it reads with nothing written, or nothing. The annotator\'s `remark` is never typed.', '');
    out.push('| Written | Thoughts |', '|---|---|');
    out.push(`| the note as it stands | ${n((t) => t.text && t.typed === undefined)} |`, `| its typed form | ${n((t) => t.typed !== undefined)} |`, `| a highlight alone | ${n((t) => !t.text && t.reads)} |`, `| nothing | ${n((t) => !t.text && !t.reads)} |`);
    out.push('', `Thoughts with a remark: ${n((t) => t.remark !== undefined)}.`);
}
out.push('', '## Dealt later than the reader has it', '', 'A RECORD whose card the game deals after the paragraph where the reader already has the fact.', '');
if (r.dateGaps.length) {
    out.push('| Thought | Card | Reader | Game |', '|---|---|---|---|');
    for (const g of r.dateGaps) out.push(`| \`${g.thought}\` | \`${g.card}\` | ¶${g.reader} | ¶${g.game} |`);
} else out.push('None.');
{
    // Notable details (workstream 5, Round 84): the cards whose marking as odd counts, and Holmes's paragraph.
    const rows = data.thoughts.filter((t) => t.notices);
    out.push('', '## Notable details', '', 'NOTICE thoughts with the cards whose marking as odd counts (`notices`). A notice scores when made before Holmes\'s paragraph; one he speaks of in its own paragraph, or never, is noticed but cannot score.', '');
    if (rows.length) {
        out.push('| Thought | Cards | Reader | Holmes | Can score |', '|---|---|---|---|---|');
        for (const t of rows) {
            const h = t.holmes?.paras?.[0];
            out.push(`| \`${t.id}\` | ${t.notices.map((x) => `\`${x}\``).join(', ')} | ¶${t.para} | ${h === undefined ? 'never' : `¶${h}`} | ${h !== undefined && h > t.para ? 'yes' : 'no'} |`);
        }
    } else out.push('None.');
}
{
    // The player's own questions (docs/questions.md, Round 152): each QUESTION thought's template, posed at its
    // paragraph by a reader who only reads on (Easy), and where it joins the story's question (if it matches one).
    const rows = data.thoughts.filter((t) => t.asks);
    const { Game: G } = await import('../engine/game.js');
    const game = new G(model, { difficulty: 'easy' });
    const ids = new Map();
    while (!game.finished()) {
        game.advance();
        for (const t of rows) if (t.para === game.read - 1) ids.set(t.id, game.pose(t.asks.template, t.asks.cards).id ?? null);
    }
    const byId = new Map(game.posedQuestions().map((q) => [q.id, q]));
    out.push('', '## Questions posed', '', 'QUESTION thoughts with the question the player can pose (`asks`), posed at the thought\'s paragraph by a reader who only reads on (Easy), and where it joins the story\'s question. One that matches no slot stays the player\'s note; joining later than it was asked is recorded, never scored.', '');
    if (rows.length) {
        out.push('| Thought | Question | Reader | Joins |', '|---|---|---|---|');
        for (const t of rows) {
            const q = byId.get(ids.get(t.id));
            out.push(`| \`${t.id}\` | ${q ? q.text : '(could not be posed)'} | ¶${t.para} | ${q?.joined ? `\`${q.joined.slot}\` at ¶${q.joined.para}` : '—'} |`);
        }
    } else out.push('None.');
}
{
    // Exceptions raised (workstream 3, Round 105): the plays that count for a thought, from where the exception shows.
    const rows = data.thoughts.filter((t) => t.raises);
    const game = new (await import('../engine/game.js')).Game(model);
    const fromPara = (x) => {
        const use = (model.data.constraints.find((k) => k.id === x.target)?.rules ?? []).find((u) => (model.cards.get(u.rule)?.unless ?? []).some((e) => e?.id === x.exception));
        if (!use) return null;
        const e = model.cards.get(use.rule).unless.find((y) => y?.id === x.exception);
        return Math.max(game.ruleAt.get(use.rule) ?? -1, e.source?.length ? model.story.find(e.source[0])?.para ?? Infinity : -1);
    };
    out.push('', '## Exceptions raised', '', 'Thoughts whose raising of an exception against an inference counts (`raises`). A raise, a reservation or a defeat, scores when made before Holmes\'s paragraph; one with no Holmes paragraph is recorded and cannot score.', '');
    if (rows.length) {
        out.push('| Thought | Against | Exception | Shows from | Holmes | Can score |', '|---|---|---|---|---|---|');
        for (const t of rows) for (const x of t.raises) {
            const h = t.holmes && !t.holmes.never ? t.holmes.paras?.[0] : undefined;
            const from = fromPara(x);
            out.push(`| \`${t.id}\` | \`${x.target}\` | ${x.exception} | ${from === null ? '—' : `¶${from}`} | ${h === undefined ? 'never' : `¶${h}`} | ${h !== undefined && from !== null && h > from ? 'yes' : 'no'} |`);
        }
    } else out.push('None.');
}
{
    // Workstream 7 (Round 127): the checks PREDICT and TEST PLAN thoughts plan (docs/predictions.md).
    const rows = model.data.thoughts.filter((t) => t.checks?.length);
    const checks = new Map((model.data.checks ?? []).map((x) => [x.id, x]));
    out.push('', '## Checks planned', '', 'PREDICT and TEST PLAN thoughts with the checks they plan (`checks`), and what they expect of the result. A sealed check scores when made before Holmes makes it, whether or not the story tells the result; an expected result must not be contradicted. A thought with no Holmes paragraph is recorded and cannot score.', '');
    if (rows.length) {
        out.push('| Thought | Check | Expects | Thought ¶ | Holmes | Result | Can score |', '|---|---|---|---|---|---|---|');
        for (const t of rows) for (const x of t.checks) {
            const ck = checks.get(x.check);
            const res = ck.result.never ? 'never' : ck.result.late !== undefined ? `late, ¶${ck.result.late}` : `¶${ck.result.shown}`;
            const dated = !!(t.holmes && !t.holmes.never && t.holmes.paras?.length);
            out.push(`| \`${t.id}\` | \`${x.check}\` | ${x.expect ?? '—'}${x.answer ? ` (${render(x.answer)})` : ''} | ¶${t.para} | ¶${ck.at} | ${res} | ${dated && t.para < ck.at ? 'yes' : 'no'} |`);
        }
    } else out.push('None.');
}
const c = r.chains;
const fmt = (p) => (p === Infinity ? 'never' : p === null ? '—' : `¶${p}`);
out.push('', '## Short chains', '', 'Each deduction-type thought (INFER, DEFAULT, AGENT, PHYSICAL, IDENTIFY) names one inference in `constraints.json` (`docs/short-chains.md`, Q1). *Dealt*: the paragraph by which the game, read through with background facts arriving where relevant, has dealt every premise of the inference (an inference premise counts once its own premises are dealt). It is also never earlier than the story deals the event cards the conclusion speaks of. A miss is a dealt paragraph later than the thought\'s own: a late card to fix, an annotation date to correct, or a miss explained (`date_note`, listed below). A deduction that can have no inference says why (`no_inference`, listed below). *Warrant*: the rules the inference applies that no cited item stands for (they need no citation); *bookkeeping*: implicit inferences among its premises; *not held*: cited thoughts no card holds yet.', '');
const isLate = (x) => x.dealt !== null && x.dealt > x.para;
out.push(`- deduction-type thoughts: ${c.rows.length}; with an inference: ${c.rows.filter((x) => x.inference).length}; with a reason for none: ${c.rows.filter((x) => x.none).length}; earliest-date misses: ${c.rows.filter((x) => isLate(x) && !x.note).length} (and ${c.rows.filter((x) => isLate(x) && x.note).length} explained); premise disagreements: ${c.rows.filter((x) => x.uncited.length || x.unmatched.length).length}`, '');
const ids = (xs) => xs.map((y) => `\`${y}\``).join(', ');
out.push('| Thought | Tag | Inference | Thought ¶ | Dealt | Cited, not a premise | Premise, not cited | Warrant | Bookkeeping | Not held |', '|---|---|---|---|---|---|---|---|---|---|');
for (const x of c.rows) {
    const miss = isLate(x) ? (x.note ? ' (explained)' : ' **late**') : '';
    out.push(`| \`${x.thought}\` | ${x.tag} | ${x.inference ? `\`${x.inference}\`` : x.none ? `none: ${x.none}` : '—'} | ¶${x.para} | ${fmt(x.dealt)}${miss} | ${ids(x.uncited)} | ${ids(x.unmatched)} | ${ids(x.warrant)} | ${ids(x.bookkeeping)} | ${ids(x.unheld)} |`);
}
const explained = c.rows.filter((x) => isLate(x) && x.note);
out.push('', '### Earliest-date misses explained', '', explained.length ? explained.map((x) => `- \`${x.thought}\` (¶${x.para}, dealt ${fmt(x.dealt)}): ${x.note}`).join('\n') : 'None.');
const none = Object.groupBy(c.rows.filter((x) => x.none), (x) => x.none);
out.push('', '### Deductions with no inference', '', 'Each says why (`no_inference`): `doubt`, the move doubts an inference rather than drawing one; `action`, a prediction played as an action; `world-model`, it needs a slot the case lacks yet; `absence`, it rests on an absence the player files (workstream 5).', '', Object.keys(none).length ? Object.entries(none).map(([why, xs]) => `- ${why}: ${xs.map((x) => `\`${x.thought}\``).join(', ')}`).join('\n') : 'None.');
out.push('', '### Inferences named by more than one thought', '', c.shared.length ? c.shared.map((x) => `- \`${x.inference}\`: ${x.thoughts.map((y) => `\`${y}\``).join(', ')}`).join('\n') : 'None.');
out.push('', '### Implicit inferences', '', 'Granted as soon as their premises are held; never gate, never score (Q4). Provisional: the world model will re-derive much of it (Q5).', '', c.implicit.length ? c.implicit.map((x) => `\`${x}\``).join(', ') : 'None.');
out.push('', '### Inferences no thought names, not marked implicit', '', 'Each must be a thought\'s inference or marked `implicit` (an error since Round 56).', '', c.unnamed.length ? c.unnamed.map((x) => `\`${x}\``).join(', ') : 'None.');
out.push('', '### Characters\' wrong reasoning', '', '`truth: false` inferences (the police\'s four): candidates for workstream 3, not reader steps.', '', c.wrong.length ? c.wrong.map((x) => `\`${x}\``).join(', ') : 'None.');
out.push('', '## Background cards with no rule', '', r.unmappedBackground.length ? r.unmappedBackground.map((b) => `\`${b}\``).join(', ') : 'None.', '');
if (r.errors.length) out.push('## Errors', '', ...r.errors.map((e) => `- ${e}`), '');
fs.writeFileSync(path.join(dir, 'thoughts-report.md'), out.join('\n'));

for (const e of r.errors) console.error(`ERROR: ${e}`);
console.log(`wrote ${path.join(dir, 'thoughts-report.md')}`);
const late = c.rows.filter((x) => x.dealt !== null && x.dealt > x.para && !x.note);
for (const x of late) console.warn(`warning: ${x.thought}: its inference ${x.inference} is dealt at ${fmt(x.dealt)}, after ¶${x.para}`);
console.log(`short chains: ${c.rows.filter((x) => x.inference).length}/${c.rows.length} deductions have an inference; ${late.length} earliest-date miss(es); ${c.unnamed.length} inference(s) neither named nor implicit`);
console.log(`${r.errors.length} error(s)`);
process.exit(r.errors.length ? 1 : 0);
