#!/usr/bin/env node
// Validate a case's annotated reading (thoughts.json) against the case and the story, and write its report.
//
//   node scripts/validate-thoughts.js cases/silver-blaze
//
// Checks (engine/thoughts.js): ids carry their paragraph and scene; tags, subtypes, confidence and profile are
// known; premises and relation targets exist and come no later; every quote is found and none lies ahead; a
// relation to one member of a set names a candidate the target lists; `maps` resolve to case cards; the data
// mirrors docs/reading-annotated.md. Reports, without failing: how many thoughts of each tag a case card holds,
// where the game deals a RECORD's card later than the reader could have it, and background cards with no rule.
// Writes <case>/thoughts-report.md.

import fs from 'node:fs';
import path from 'node:path';
import { loadCase } from '../engine/loadCase.js';
import { checkThoughts } from '../engine/thoughts.js';

const dir = process.argv[2];
if (!dir) {
    console.error('usage: validate-thoughts.js <case dir>');
    process.exit(2);
}
const model = await loadCase(dir);
const data = JSON.parse(fs.readFileSync(path.join(dir, 'thoughts.json'), 'utf8'));
const mdPath = new URL('../docs/reading-annotated.md', import.meta.url);
const markdown = fs.existsSync(mdPath) ? fs.readFileSync(mdPath, 'utf8') : null;
const r = checkThoughts(data, model, { markdown, dates: true });

const out = [];
out.push(`# Thoughts report: ${model.data.case.title}`, '', 'Generated by `scripts/validate-thoughts.js`. Do not edit by hand.', '');
out.push(`- thoughts: ${data.thoughts.length}; background cards: ${data.background.length}`);
out.push(`- errors: ${r.errors.length}`, '');
out.push('## Coverage', '', 'Thoughts of each tag whose content some case card holds (`maps`): a claim, rule, inference, question, action, route step or theory. A thought with no card is a gap in the data. Held content is not yet a move the player can make: the moves are the workstreams of `docs/gap-analysis.md`.', '');
out.push('| Tag | Thoughts | Held by a card |', '|---|---|---|');
for (const c of r.coverage) out.push(`| ${c.tag} | ${c.count} | ${c.mapped} |`);
out.push('', '## Dealt later than the reader has it', '', 'A RECORD whose card the game deals after the paragraph where the reader already has the fact.', '');
if (r.dateGaps.length) {
    out.push('| Thought | Card | Reader | Game |', '|---|---|---|---|');
    for (const g of r.dateGaps) out.push(`| \`${g.thought}\` | \`${g.card}\` | ¶${g.reader} | ¶${g.game} |`);
} else out.push('None.');
out.push('', '## Background cards with no rule', '', r.unmappedBackground.length ? r.unmappedBackground.map((b) => `\`${b}\``).join(', ') : 'None.', '');
if (r.errors.length) out.push('## Errors', '', ...r.errors.map((e) => `- ${e}`), '');
fs.writeFileSync(path.join(dir, 'thoughts-report.md'), out.join('\n'));

for (const e of r.errors) console.error(`ERROR: ${e}`);
console.log(`wrote ${path.join(dir, 'thoughts-report.md')}`);
console.log(`${r.errors.length} error(s)`);
process.exit(r.errors.length ? 1 : 0);
